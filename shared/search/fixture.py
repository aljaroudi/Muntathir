"""Regenerate shared/fixtures/quran-spelling.json (and the Apple test copy) from quran_spelling.py.

The vocabulary holds the real index entries each case can resolve to, so every platform
reproduces the result it would get from the full Quran index.
"""
import json
from pathlib import Path
import sqlite3
import sys

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
from quran_spelling import Vocabulary, candidates, fold, resolve  # noqa: E402

ROOT = HERE.parents[1]
TYPED = ("الصلاة الزكاة الحياة السماوات الإنسان الصالحات خالدين إبراهيم إسرائيل الملائكة الملايكة الكتاب النبيين "
         "آمنوا امنوا القرآن القران جنات القيامة الربا المومنين المؤمنين آدم الله محمد كاتب كمبيوتر عيسى موسى "
         "الحمد لله رب العالمين الرحمن الرحيم هذا ذلك لكن يا").split()
PREFIXES = ("الصلا", "الكتا", "الملاي", "الصال", "ابراه", "خالد")
FOLDS = ("الصَّلَاةُ", "إِبْرَاهِيمَ", "آمَنُوا", "مُؤْمِنَةٍ", "عِيسَى", "ٱلرَّحْمَٰنِ", "الرَّحمـٰنِ", "أَحَدٌ", "ءَامَنُوا")
SPELLINGS = ("الصلاه", "النبيين", "جنات", "امنوا")


def main():
    db = sqlite3.connect((ROOT / "apple/Muntathir/Resources/Quran/quran.db").as_uri() + "?mode=ro", uri=True)
    full = Vocabulary(db.execute("select term, doc from quran_words_vocab"))
    cases = [(word, False) for word in TYPED] + [(word, True) for word in PREFIXES]
    needed = set()
    for word, prefix in cases:
        key = fold(word)
        for spelling in candidates(key):
            needed |= {t for t in full.sorted if (t.startswith(spelling) if prefix else t == spelling)}
    vocabulary = {term: full.docs[term] for term in sorted(needed)}
    subset = Vocabulary(vocabulary.items())
    out = {
        "_comment": "Generated by shared/search/fixture.py; the Swift and Kotlin Quran readers must agree on every case.",
        "fold": [{"text": text, "key": fold(text)} for text in FOLDS],
        "vocabulary": [{"term": term, "docs": docs} for term, docs in vocabulary.items()],
        "cases": [{"typed": word, "prefix": prefix, "resolved": resolve(fold(word), subset, prefix)} for word, prefix in cases],
        "candidates": [{"key": key, "spellings": dict(sorted(candidates(key).items()))} for key in SPELLINGS],
    }
    for case in out["cases"]:
        assert case["resolved"] == resolve(fold(case["typed"]), full, case["prefix"]), case
    text = json.dumps(out, ensure_ascii=False, indent=2) + "\n"
    for path in ("shared/fixtures/quran-spelling.json", "apple/MuntathirTests/Fixtures/quran-spelling.json"):
        (ROOT / path).write_text(text)
    print(len(vocabulary), "terms;", sum(c["resolved"] != fold(c["typed"]) for c in out["cases"]), "cases rewritten")


main()
