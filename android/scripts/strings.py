#!/usr/bin/env python3
"""Generate Android string resources from the Apple catalogs (single source of truth).

Reads apple/Muntathir/Localizable.xcstrings and <locale>.lproj/InfoPlist.strings and writes
app/src/main/res/values*/strings.xml. Android-only strings belong in strings_android.xml.

    python3 android/scripts/strings.py          # write
    python3 android/scripts/strings.py --check  # fail if the output is stale
"""

import hashlib
import json
import re
import sys
from pathlib import Path

ANDROID = Path(__file__).resolve().parents[1]
APPLE = ANDROID.parent / "apple/Muntathir"
RES = ANDROID / "app/src/main/res"
SOURCE = "en"
QUALIFIERS = {
    "en": "values",
    "ar": "values-ar",
    "de": "values-de",
    "es": "values-es",
    "fa": "values-fa",
    "fr": "values-fr",
    "id": "values-in",
    "it": "values-it",
    "ja": "values-ja",
    "ms": "values-ms",
    "ru": "values-ru",
    "tr": "values-tr",
    "ur": "values-ur",
    "zh-Hans": "values-b+zh+Hans",
    "zh-Hant": "values-b+zh+Hant",
}
INFO_PLIST = {
    "CFBundleDisplayName": "app_name",
    "NSLocationWhenInUseUsageDescription": "location_rationale",
    "QiblaPreciseLocation": "precise_location_rationale",
    "NSCameraUsageDescription": "camera_rationale",
}
# Resource names become R.string fields, so Java keywords and literals are invalid.
JAVA_KEYWORDS = set(
    "abstract assert boolean break byte case catch char class const continue default do double else enum "
    "extends final finally float for goto if implements import instanceof int interface long native new "
    "package private protected public return short static strictfp super switch synchronized this throw "
    "throws transient try void volatile while true false null".split()
)
# CLDR integer plural categories that Android lint (MissingQuantity) requires per locale.
PLURAL_CATEGORIES = {
    "ar": ("zero", "one", "two", "few", "many", "other"),
    "ru": ("one", "few", "many", "other"),
    **{locale: ("one", "other") for locale in ("en", "de", "es", "fa", "fr", "it", "tr", "ur")},
    **{locale: ("other",) for locale in ("id", "ja", "ms", "zh-Hans", "zh-Hant")},
}
HEADER = "<!-- Generated by android/scripts/strings.py from the Apple catalogs. Do not edit. -->"
PLACEHOLDER = re.compile(r"%(?:(\d+)\$)?(@|lld|ld|d|(?:\.\d+)?f)|%%")


def resource_name(key):
    slug = re.sub(r"%(\d+\$)?(@|lld|ld|d|(\.\d+)?f)", " x ", key).lower()
    slug = re.sub(r"[^a-z0-9]+", "_", slug).strip("_")[:48].rstrip("_")
    if not slug or slug[0].isdigit():
        slug = f"s_{slug}".rstrip("_")
    return f"{slug}_text" if slug in JAVA_KEYWORDS else slug


def names(keys):
    """Readable, deterministic names; colliding slugs all get a short hash suffix."""
    slugs = {key: resource_name(key) for key in keys}
    taken = {}
    for slug in slugs.values():
        taken[slug] = taken.get(slug, 0) + 1
    reserved = set(INFO_PLIST.values())
    return {
        key: f"{slug}_{hashlib.sha1(key.encode()).hexdigest()[:6]}" if taken[slug] > 1 or slug in reserved else slug
        for key, slug in slugs.items()
    }


def android_format(text):
    """Apple placeholders → Java format specifiers, positional when there are several."""
    matches = [m for m in PLACEHOLDER.finditer(text) if m.group(0) != "%%"]
    if not matches:
        return text.replace("%%", "%")
    numbered = len(matches) > 1
    counter = 0

    def convert(match):
        nonlocal counter
        if match.group(0) == "%%":
            return "%%"
        counter += 1
        position = match.group(1) or (str(counter) if numbered else None)
        kind = match.group(2)
        conversion = "s" if kind == "@" else "d" if kind in ("lld", "ld", "d") else kind
        return f"%{position}${conversion}" if position else f"%{conversion}"

    return PLACEHOLDER.sub(convert, text)


def escape(text):
    text = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    return "\\" + text if text[:1] in ("@", "?") else text


def units(value):
    """Returns {"other": text} for plain strings, or the plural category map."""
    if "stringUnit" in value:
        return {"other": value["stringUnit"]["value"]}
    plural = value.get("variations", {}).get("plural")
    return {category: child["stringUnit"]["value"] for category, child in plural.items()} if plural else {}


def info_plist(locale):
    path = APPLE / f"{locale}.lproj/InfoPlist.strings"
    pairs = dict(re.findall(r'^"([^"]+)"\s*=\s*"((?:[^"\\]|\\.)*)";', path.read_text(), re.M)) if path.exists() else {}
    return {name: pairs[key].replace('\\"', '"') for key, name in INFO_PLIST.items() if key in pairs}


def render(locale, catalog, resource_names):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', HEADER, "<resources>"]
    for name, text in info_plist(locale).items():
        lines.append(f'    <string name="{name}">{escape(text)}</string>')
    for key in sorted(catalog):
        entry = catalog[key]
        translatable = entry.get("shouldTranslate", True)
        if not translatable and locale != SOURCE:
            continue
        localized = entry.get("localizations", {}).get(locale)
        forms = units(localized) if localized else ({"other": key} if locale == SOURCE else {})
        if not forms:
            continue
        name = resource_names[key]
        attribute = "" if translatable else ' translatable="false"'
        plural = any(units(v).keys() - {"other"} for v in entry.get("localizations", {}).values())
        if plural:
            lines.append(f'    <plurals name="{name}"{attribute}>')
            # Catalogs often store only "other" when the translation doesn't vary; reuse it for the
            # categories the locale requires so every count resolves to the translated text.
            categories = [q for q in PLURAL_CATEGORIES[locale] if q in forms or "other" in forms]
            categories += [q for q in forms if q not in categories]
            lines += [
                f'        <item quantity="{q}">{escape(android_format(forms.get(q, forms["other"])))}</item>'
                for q in categories
            ]
            lines.append("    </plurals>")
        else:
            lines.append(f'    <string name="{name}"{attribute}>{escape(android_format(forms["other"]))}</string>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def main():
    catalog = json.loads((APPLE / "Localizable.xcstrings").read_text())["strings"]
    # Pure-format keys such as "%@ %@" are composed in Kotlin instead.
    catalog = {k: v for k, v in catalog.items() if re.search(r"[^\W\d_]", PLACEHOLDER.sub("", k))}
    resource_names = names(catalog)
    stale = []
    for locale, qualifier in QUALIFIERS.items():
        path = RES / qualifier / "strings.xml"
        output = render(locale, catalog, resource_names)
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != output:
                stale.append(str(path.relative_to(ANDROID)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(output)
    if stale:
        raise SystemExit("Stale strings; run `just android-strings`:\n" + "\n".join(stale))
    print(f"{'Checked' if '--check' in sys.argv else 'Wrote'} {len(catalog)} strings in {len(QUALIFIERS)} locales.")


if __name__ == "__main__":
    main()
